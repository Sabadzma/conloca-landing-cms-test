import { readdir, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const iconsDirectory = fileURLToPath(
  new URL("../Conloca Design system/icons", import.meta.url),
)
const outputFile = fileURLToPath(
  new URL(
    "../Conloca Design system/components/conloca-icon/icon-names.generated.ts",
    import.meta.url,
  ),
)

const iconNames = (await readdir(iconsDirectory))
  .filter((filename) => filename.endsWith(".svg"))
  .map((filename) => filename.slice(0, -".svg".length))
  .toSorted((firstName, secondName) => firstName.localeCompare(secondName))

const typeMembers = iconNames.map((name) => `  | ${JSON.stringify(name)}`).join("\n")
const output = `// Generated by \`bun run icons:generate\`. Do not edit manually.\nexport type ConlocaIconName =\n${typeMembers}\n`

await writeFile(outputFile, output)
